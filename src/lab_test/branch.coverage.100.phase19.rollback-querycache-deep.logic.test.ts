describe("Branch coverage 100% - phase 19 rollback/query-cache deep branches", () => {
  beforeEach(() => {
    jest.spyOn(console, "log").mockImplementation(() => undefined);
    jest.spyOn(console, "warn").mockImplementation(() => undefined);
    jest.spyOn(console, "error").mockImplementation(() => undefined);
  });

  afterEach(async () => {
    HookStore.clear();
    ModelRegistry.clear();
    await CacheRegistry.clearAll().catch(() => undefined);
    jest.restoreAllMocks();
    jest.resetModules();
    process.exitCode = 0;
  });

  test("covers QueryCache model-name fallback and hasModelDefaults branch permutations", async () => {
    Object.defineProperty(Phase19CacheModel, "name", { value: "", configurable: true });
    const model = new Phase19CacheModel();

    const clearModelSpy = jest.spyOn(CacheRegistry, "clearModel").mockResolvedValue(undefined);
    const clearGroupSpy = jest.spyOn(CacheRegistry, "clearGroup").mockResolvedValue(undefined);
    const cacheGetSpy = jest.spyOn(CacheManager, "get").mockResolvedValue(null);
    const cacheSetSpy = jest.spyOn(CacheManager, "set").mockResolvedValue(undefined);
    const addKeySpy = jest.spyOn(CacheRegistry, "addKey").mockImplementation(() => undefined);

    // Hook registration uses fallback model name "Model".
    const hooks = HookStore.snapshot(Phase19CacheModel as any);
    expect(hooks.created).toHaveLength(1);
    await hooks.created[0]({} as any);
    expect(clearModelSpy).toHaveBeenCalledWith("Model");
    await model.invalidateCacheGroup("groupA");
    expect(clearGroupSpy).toHaveBeenCalledWith("Model", "groupA");

    const executeSpy = jest.fn(async () => "value");
    const ctor = model.constructor as typeof Phase19CacheModel;

    // no defaults -> fast path
    delete ctor.defaultCacheTTL;
    delete ctor.cacheStrategy;
    delete ctor.cacheTTL;
    model.disable();
    await model.runCached({ page: 1 }, executeSpy, "g0");
    expect(cacheGetSpy).not.toHaveBeenCalled();

    // defaultCacheTTL only -> caching path
    ctor.defaultCacheTTL = 10;
    await model.runCached({ page: 2 }, executeSpy, "g1");
    expect(cacheGetSpy).toHaveBeenCalled();

    // cacheStrategy only -> caching path
    delete ctor.defaultCacheTTL;
    ctor.cacheStrategy = () => 7;
    await model.runCached({ page: 3 }, executeSpy, "g2");

    // cacheTTL empty -> fast path
    delete ctor.cacheStrategy;
    ctor.cacheTTL = {};
    cacheGetSpy.mockClear();
    await model.runCached({ page: 4 }, executeSpy, "g3");
    expect(cacheGetSpy).not.toHaveBeenCalled();

    // cacheTTL non-empty -> caching path and Model-prefixed key branch
    ctor.cacheTTL = { g4: 12 };
    model.enable(5);
    await model.runCached({ page: 5 }, executeSpy);
    expect(cacheSetSpy).toHaveBeenCalled();
    expect(addKeySpy).toHaveBeenCalled();
    expect(cacheGetSpy).toHaveBeenCalledWith(expect.stringMatching(/^Model:default:/));
  });

  test("covers migrateRollback pg-cascade fallback, sort/id-nullish path, and default connection resolution", async () => {
    const rows: RollbackRow[] = [
      { id: undefined, name: "20260309091001001_create_alphas_table.ts", batch: 2 },
      { id: 3, name: "20260309091001002_create_betas_table.ts", batch: 2 },
      { id: 1, name: "20260309091001003_create_gammas_table.ts", batch: 1 },
    ];
    const harness = await setupPgRollbackHarness(rows);

    await harness.migrateRollback({
      test: true,
      connectionNames: ["pg" as any],
      allMigrations: true,
    });

    expect(harness.db.execute).toHaveBeenCalledWith(
      expect.stringContaining("CASCADE"),
      []
    );
    const deletedNames = (harness.mocks.deleteAppliedMigration.mock.calls as Array<any[]>).map(
      (c) => c[1]
    );
    expect(deletedNames).toEqual([
      "20260309091001002_create_betas_table.ts",
      "20260309091001001_create_alphas_table.ts",
      "20260309091001003_create_gammas_table.ts",
    ]);
    expect(harness.mocks.appendAuditEvent).toHaveBeenCalledWith(
      expect.objectContaining({ test: true, result: "success" })
    );

    harness.mocks.deleteAppliedMigration.mockClear();
    harness.mocks.resolveConnectionName.mockClear();
    await harness.migrateRollback({ test: true, allMigrations: true });
    expect(harness.mocks.resolveConnectionName).toHaveBeenCalledWith(undefined, { test: true });

    fs.rmSync(harness.root, { recursive: true, force: true });
  });
});
