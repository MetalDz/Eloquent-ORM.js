const passthroughChalk = {
  __esModule: true,
  default: {
    gray: (v: string) => v,
    yellow: (v: string) => v,
    cyan: (v: string) => v,
    green: (v: string) => v,
    greenBright: (v: string) => v,
    red: (v: string) => v,
  },
};

abstract class EmptyBase {}

class Phase19CacheModel extends QueryCacheMixin(
  EmptyBase as unknown as abstract new (...args: any[]) => object
) {
  enable(ttl = 60): this {
    return (this as any).cache(ttl);
  }

  disable(): this {
    return (this as any).withoutCache();
  }

  runCached<T>(payload: unknown, execute: () => Promise<T>, group = "default"): Promise<T> {
    return (this as any).runWithCache(payload, execute, group);
  }
}

type RollbackRow = { id?: number; name: string; batch: number };

